def finding(identifier="arxiv:2610.08098", authors=("Ada Lovelace", "Alan Turing", "Grace Hopper"), summary="Abstract."):
    return Finding(
        id=identifier,
        source="arXiv",
        category="arxiv",
        url=f"https://arxiv.org/abs/{identifier.split(':')[1]}",
        title="Surviving the Router",
        summary=summary,
        published=date(2026, 10, 9),
        authors=list(authors),
        tier="preprint",
        source_kind="primary_research",
        fetched_at=NOW,
    )


def test_article_text_keeps_the_body_and_formulas_but_not_references_or_appendix():
    text = arxiv_article_text(ARTICLE)

    assert text.startswith("Surviving the Router")
    assert "Skills compete for retrieval.\nSecond line." in text
    assert "r=0.9" in text and "<mi>" not in text
    assert "Ada Lovelace" not in text and "Doe, J." not in text and "Extra tables" not in text
    assert "LaTeXML" not in text


def test_source_text_uses_and_caches_the_html_version(tmp_path):
    calls = []

    def fetch(url):
        calls.append(url)
        return ARTICLE

    first = source_text(finding(), fetch=fetch, cache_directory=tmp_path)
    second = source_text(finding(), fetch=fetch, cache_directory=tmp_path)

    assert first.full_text and "r=0.9" in first.text
    assert second.text == first.text and calls == ["https://arxiv.org/html/2610.08098"]
    assert first.short == "Lovelace et al. (2026)"


def test_source_text_falls_back_to_the_summary(tmp_path):
    def fetch(url):
        raise OSError("404")

    result = source_text(finding(summary="Only the abstract."), fetch=fetch, cache_directory=tmp_path)

    assert not result.full_text and result.text == "Only the abstract."


def test_citations_name_one_two_or_many_authors():
    assert short_citation(finding(authors=("Ada Lovelace",))) == "Lovelace (2026)"
    assert short_citation(finding(authors=("Ada Lovelace", "Alan Turing"))) == "Lovelace & Turing (2026)"
    feed_item = Finding(**{**finding(identifier="rss:1", authors=()).__dict__, "source": "OpenAI News"})
    assert short_citation(feed_item) == "OpenAI News (2026)"


def test_passages_are_paragraph_aligned_and_labelled(tmp_path):
    summary = "\n".join(f"Paragraph {i} " + "word " * 50 for i in range(6))
    source = source_text(finding(summary=summary), fetch=lambda url: "", cache_directory=tmp_path)

    result = passages(source, size=600)

    assert len(result) == 3
    assert all(passage.startswith("[Lovelace et al. (2026)] Paragraph") for passage in result)


def test_originality_measures_verbatim_eight_grams():
    source = "Prompt injection lets attackers control an agent through web pages or documents it reads."
    copied = "As noted, prompt injection lets attackers control an agent through web pages or documents it reads."
    rewritten = "Attackers can steer agents by hiding instructions in content that the agent retrieves."

    copied_report = originality(copied, [source])
    rewritten_report = originality(rewritten, [source])

    assert copied_report.copied_share > 0.5 and not copied_report.passed
    assert copied_report.copied_passages[0].startswith("prompt injection lets attackers")
    assert rewritten_report.copied_share == 0 and rewritten_report.passed


